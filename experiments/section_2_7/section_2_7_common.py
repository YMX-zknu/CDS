def ensure_dir(path: Path) -> Path:
    path.mkdir(parents=True, exist_ok=True)
    return path


def save_json(obj, path: Path):
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(obj, f, indent=2, ensure_ascii=False)


def parse_float_list(text: str) -> List[float]:
    return [float(x) for x in str(text).split(",") if x.strip()]


def dataclass_from_checkpoint(config_cls, checkpoint: dict, overrides: Optional[dict] = None):
    raw = dict(checkpoint.get("config", {}))
    raw.update(overrides or {})
    accepted = {f.name for f in fields(config_cls)}
    return config_cls(**{k: v for k, v in raw.items() if k in accepted})


def normalize_dataset_splits(build_output):
    if not isinstance(build_output, (tuple, list)):
        raise TypeError("Dataset builder must return a tuple/list.")
    if len(build_output) == 2:
        return build_output[0], build_output[1]
    raise ValueError(f"Expected exactly 2 dataset splits (train, test), received {len(build_output)}.")


def checkpoint_path(results_root: Path, dataset: str, seed: int, model: str,
                    ablation_root: Optional[Path] = None) -> Path:
    if model == "constant_release":
        if ablation_root is None:
            raise FileNotFoundError("constant_release requested without --ablation_root")
        candidates = [
            ablation_root / "ablation_runs" / "constant_release" / dataset / f"seed_{seed}" / "checkpoints" / "cds.pt",
            ablation_root / "constant_release" / dataset / f"seed_{seed}" / "checkpoints" / "cds.pt",
        ]
    else:
        candidates = [
            results_root / dataset / f"seed_{seed}" / "checkpoints" / f"{model}.pt",
            results_root / dataset / f"seed_{seed}" / "checkpoints" / f"best_{model}.pt",
        ]
    for path in candidates:
        if path.exists():
            return path
    raise FileNotFoundError("Checkpoint not found. Checked:\n" + "\n".join(map(str, candidates)))


def load_checkpoint_file(path: Path, device: torch.device) -> dict:
    obj = load_torch_file(path, map_location=device)
    if isinstance(obj, dict) and "model_state" in obj:
        return obj
    if isinstance(obj, dict) and "state_dict" in obj:
        return {"model_state": obj["state_dict"], "config": obj.get("config", {})}
    if isinstance(obj, dict):
        return {"model_state": obj, "config": {}}
    raise TypeError(f"Unsupported checkpoint format: {path}")


def verify_matched_checkpoint_configs(checkpoints: Dict[str, Tuple[Path, dict]]) -> None:

    reference = dict(checkpoints["static"][1].get("config", {}))
    ignored = {"model", "cds_variant", "out_dir"}
    for label, (path, checkpoint) in checkpoints.items():
        if label == "static":
            continue
        candidate = dict(checkpoint.get("config", {}))
        mismatches = {
            key: (reference.get(key), candidate.get(key))
            for key in sorted(set(reference).intersection(candidate) - ignored)
            if reference.get(key) != candidate.get(key)
        }
        if mismatches:
            preview = ", ".join(
                f"{key}: {left!r} != {right!r}"
                for key, (left, right) in list(mismatches.items())[:8]
            )
            raise RuntimeError(
                f"Checkpoint {path} is not configuration-matched to the static "
                f"checkpoint ({preview}). Use checkpoints generated by the same "
                "Section 2.6 task run."
            )


class ScalarHookRecorder:

    def __init__(self, model: nn.Module):
        self.model = model
        self.handles = []
        self.records: Dict[str, List[dict]] = {}
        self._register()

    def _hook(self, name: str):
        def fn(_module, _inputs, output):
            y = output[0] if isinstance(output, (tuple, list)) else output
            y = y.detach()
            self.records.setdefault(name, []).append({
                "sum": float(y.sum().cpu()),
                "abs_sum": float(y.abs().sum().cpu()),
                "nonzero": float((y != 0).sum().cpu()),
                "numel": int(y.numel()),
                "shape": tuple(int(v) for v in y.shape),
            })
        return fn

    def _add(self, module, name):
        self.handles.append(module.register_forward_hook(self._hook(name)))

    def _register(self):
        m = self.model
        if hasattr(m, "convs") and hasattr(m, "pools"):
            for i, cds in enumerate(getattr(m, "cds_layers", [])):
                self._add(cds, f"block{i+1}_cds")
            for i, lif in enumerate(m.lifs):
                self._add(lif, f"block{i+1}_lif")
            for i, pool in enumerate(m.pools):
                self._add(pool, f"block{i+1}_pool")
            self._add(m.adaptive_pool, "fc1_input")
            self._add(m.lif_fc1, "fc1_lif")
            self._add(m.lif_fc2, "fc2_lif")
            self.kind = "conv"
        elif hasattr(m, "linears") and hasattr(m, "lifs"):
            for i, cds in enumerate(getattr(m, "cds_layers", [])):
                self._add(cds, f"fc{i+1}_cds")
            for i, lif in enumerate(m.lifs):
                self._add(lif, f"fc{i+1}_lif")
            self._add(m.lif_out, "out_lif")
            self.kind = "mlp"
        else:
            raise TypeError(f"Unsupported model class for Section 2.7: {type(m).__name__}")

    def clear(self):
        self.records = {}

    def close(self):
        for h in self.handles:
            h.remove()
        self.handles = []


def _record_at(records: Dict[str, List[dict]], name: str, t: int) -> dict:
    seq = records.get(name, [])
    if t >= len(seq):
        raise RuntimeError(f"Hook {name} recorded {len(seq)} calls, expected time index {t}.")
    return seq[t]


def _input_nonzero_per_t(x_seq: torch.Tensor) -> List[float]:
    return [float((x_seq[t] != 0).sum().detach().cpu()) for t in range(x_seq.shape[0])]


def _input_abs_sum_per_t(x_seq: torch.Tensor) -> List[float]:

    return [float(x_seq[t].abs().sum().detach().cpu()) for t in range(x_seq.shape[0])]


def operation_rows_from_hooks(model: nn.Module, recorder: ScalarHookRecorder,
                              x_seq: torch.Tensor, dataset: str, model_label: str,
                              perturbation_ratio: float, batch_index: int) -> Tuple[List[dict], List[dict]]:

    T, B = int(x_seq.shape[0]), int(x_seq.shape[1])
    input_nz = _input_nonzero_per_t(x_seq)
    input_abs = _input_abs_sum_per_t(x_seq)
    temporal, layer_acc = [], {}

    def add_layer(layer, t, input_events, input_signal, output_rec, fanout, input_kind,
                  cds_rec=None):
        output_spikes = float(output_rec["sum"])
        output_units = int(output_rec["numel"])
        ops = float(input_events) * float(fanout)


        weighted_propagation = float(input_signal) * float(fanout)


        mac_ops = ops if input_kind in {"analog", "graded"} else 0.0
        analog_mac_ops = ops if input_kind == "analog" else 0.0
        graded_mac_ops = ops if input_kind == "graded" else 0.0
        ac_ops = ops if input_kind == "spike" else 0.0
        cds_modulation_elements = float(cds_rec["numel"]) if cds_rec is not None else 0.0
        cds_state_elements = (
            cds_modulation_elements
            if cds_rec is not None and model_label != "constant_release"
            else 0.0
        )
        temporal.append({
            "dataset": dataset, "model": model_label,
            "perturbation_ratio": perturbation_ratio,
            "batch": batch_index, "t": t, "layer": layer,
            "batch_size": B, "output_spikes": output_spikes,
            "output_units": output_units, "mean_spike_activity": output_spikes / max(output_units, 1),
            "input_event_count": float(input_events), "fanout": float(fanout),
            "mac_ops": mac_ops, "analog_mac_ops": analog_mac_ops,
            "graded_mac_ops": graded_mac_ops, "ac_ops": ac_ops, "synops": ops,
            "transmission_weighted_propagation": weighted_propagation,
            "neuron_updates": float(output_units), "input_kind": input_kind,
            "cds_modulation_elements": cds_modulation_elements,
            "cds_state_elements": cds_state_elements,
        })
        acc = layer_acc.setdefault(layer, {"mac_ops": 0.0, "analog_mac_ops": 0.0,
                                            "graded_mac_ops": 0.0, "ac_ops": 0.0, "synops": 0.0,
                                            "transmission_weighted_propagation": 0.0,
                                            "neuron_updates": 0.0, "output_spikes": 0.0,
                                            "output_units": 0.0,
                                            "cds_modulation_elements": 0.0,
                                            "cds_state_elements": 0.0})
        for key, value in [("mac_ops", mac_ops), ("analog_mac_ops", analog_mac_ops),
                           ("graded_mac_ops", graded_mac_ops), ("ac_ops", ac_ops), ("synops", ops),
                           ("transmission_weighted_propagation", weighted_propagation),
                           ("neuron_updates", output_units), ("output_spikes", output_spikes),
                           ("output_units", output_units),
                           ("cds_modulation_elements", cds_modulation_elements),
                           ("cds_state_elements", cds_state_elements)]:
            acc[key] += float(value)

    if recorder.kind == "conv":
        for t in range(T):
            for i, conv in enumerate(model.convs):
                layer = f"block{i+1}"
                output = _record_at(recorder.records, f"block{i+1}_lif", t)
                if model_label != "static":
                    cds_rec = _record_at(recorder.records, f"block{i+1}_cds", t)
                    in_events, in_signal, kind = cds_rec["nonzero"], cds_rec["abs_sum"], "graded"
                elif i == 0:
                    cds_rec = None
                    in_events, in_signal, kind = input_nz[t], input_abs[t], "analog"
                else:
                    cds_rec = None
                    previous = _record_at(recorder.records, f"block{i}_pool", t)
                    in_events, in_signal = previous["sum"], previous["abs_sum"]
                    kind = "spike"
                kernel = conv.kernel_size[0] * conv.kernel_size[1]
                fanout = kernel * conv.out_channels / max(conv.groups, 1)
                add_layer(layer, t, in_events, in_signal, output, fanout, kind, cds_rec)

            fc1_record = _record_at(recorder.records, "fc1_input", t)
            fc1_in = fc1_record["nonzero"]
            add_layer("fc1", t, fc1_in, fc1_record["abs_sum"], _record_at(recorder.records, "fc1_lif", t),
                      model.fc1.out_features, "analog")
            fc2_record = _record_at(recorder.records, "fc1_lif", t)
            fc2_in = fc2_record["sum"]
            add_layer("fc2", t, fc2_in, fc2_record["abs_sum"], _record_at(recorder.records, "fc2_lif", t),
                      model.fc2.out_features, "spike")
    else:
        for t in range(T):
            for i, linear in enumerate(model.linears):
                if model_label != "static":
                    cds_rec = _record_at(recorder.records, f"fc{i+1}_cds", t)
                    in_events, in_signal, kind = cds_rec["nonzero"], cds_rec["abs_sum"], "graded"
                elif i == 0:
                    cds_rec = None
                    in_events, in_signal, kind = input_nz[t], input_abs[t], "analog"
                else:
                    cds_rec = None
                    previous = _record_at(recorder.records, f"fc{i}_lif", t)
                    in_events, in_signal = previous["sum"], previous["abs_sum"]
                    kind = "spike"
                add_layer(f"fc{i+1}", t, in_events,
                          in_signal,
                          _record_at(recorder.records, f"fc{i+1}_lif", t),
                          linear.out_features, kind, cds_rec)
            readout_record = _record_at(recorder.records, f"fc{len(model.linears)}_lif", t)
            readout_in = readout_record["sum"]
            add_layer("out", t, readout_in, readout_record["abs_sum"], _record_at(recorder.records, "out_lif", t),
                      model.readout.out_features, "spike")

    layer_rows = []
    for layer, acc in layer_acc.items():
        layer_rows.append({
            "dataset": dataset, "model": model_label,
            "perturbation_ratio": perturbation_ratio,
            "batch": batch_index, "layer": layer, "batch_size": B,
            **acc, "mean_spike_activity": acc["output_spikes"] / max(acc["output_units"], 1),
        })
    return temporal, layer_rows


def _as_output_and_dynamics(model, x_seq, record_cds: bool):
    if record_cds:
        output, dynamics = model(
            x_seq, return_dynamics=True, return_input_release=True
        )
        return output, dynamics
    return model(x_seq), None


def _append_cds_rows(target: List[dict], dynamics: Optional[dict], dataset: str,
                     model_label: str, perturbation_ratio: float, batch_index: int,
                     batch_size: int):
    if not dynamics:
        return
    for row in dynamics.get("cds_stats", []):
        out = dict(row)
        out.update({"dataset": dataset, "model": model_label,
                    "perturbation_ratio": perturbation_ratio,
                    "batch": batch_index, "batch_size": batch_size})
        target.append(out)


@torch.no_grad()
def evaluate_checkpoint(model: nn.Module, model_label: str, loader: DataLoader,
                        device: torch.device, cfg, num_classes: int, dataset: str,
                        perturbation_ratio: float, perturbation_seed: int,
                        isolation_guard_steps: int,
                        minimum_realized_fraction: float,
                        max_batches: int = 0) -> Dict[str, object]:
    model.eval()
    recorder = ScalarHookRecorder(model)
    confusion = np.zeros((num_classes, num_classes), dtype=np.int64)
    temporal_rows, layer_rows, cds_rows = [], [], []
    total_added = total_original = total_target = total_available = 0
    supported_release_sum = isolated_release_sum = 0.0
    supported_count = isolated_count = 0
    n_samples = 0
    try:
        for batch_index, (frame, label) in enumerate(loader):
            if max_batches > 0 and batch_index >= max_batches:
                break
            x_seq = to_time_first(frame, device)
            y = labels_to_device(label, device)
            perturbation = add_amplitude_matched_isolated_perturbations(
                x_seq,
                perturbation_ratio,
                seed=int(perturbation_seed + 1000003 * batch_index),
                guard_steps=isolation_guard_steps,
                minimum_realized_fraction=minimum_realized_fraction,
            )
            x_perturbed = perturbation.perturbed
            total_added += int(perturbation.n_added)
            total_original += int(perturbation.n_original)
            total_target += int(perturbation.n_target)
            total_available += int(perturbation.n_available)
            recorder.clear()
            output, dynamics = _as_output_and_dynamics(
                model, x_perturbed, model_label != "static"
            )
            if model_label != "static":
                release = dynamics.get("input_release_seq")
                if release is None:
                    raise RuntimeError(
                        "The CDS model did not return input-layer release "
                        "probabilities required for transmission selectivity."
                    )
                supported_values = release[
                    perturbation.supported_original_mask
                ]
                isolated_values = release[perturbation.added_mask]
                supported_release_sum += float(supported_values.sum().cpu())
                isolated_release_sum += float(isolated_values.sum().cpu())
                supported_count += int(supported_values.numel())
                isolated_count += int(isolated_values.numel())
            else:
                batch_supported = int(
                    perturbation.supported_original_mask.sum().item()
                )
                batch_isolated = int(perturbation.added_mask.sum().item())
                supported_release_sum += float(batch_supported)
                isolated_release_sum += float(batch_isolated)
                supported_count += batch_supported
                isolated_count += batch_isolated
            logits = output.mean(0)
            pred = logits.argmax(1)
            for gt, pr in zip(y.cpu().numpy(), pred.cpu().numpy()):
                confusion[int(gt), int(pr)] += 1
            tr, lr = operation_rows_from_hooks(
                model, recorder, x_perturbed, dataset, model_label,
                perturbation_ratio, batch_index
            )
            temporal_rows.extend(tr); layer_rows.extend(lr)
            _append_cds_rows(cds_rows, dynamics, dataset, model_label,
                             perturbation_ratio,
                             batch_index, int(y.numel()))
            n_samples += int(y.numel())
            reset_net(model)
    finally:
        recorder.close()

    realized_target_fraction = (
        total_added / total_target if total_target > 0 else 1.0
    )
    if (
        total_target > 0
        and realized_target_fraction + 1e-12 < float(minimum_realized_fraction)
    ):
        raise RuntimeError(
            "The analysed test split cannot realize the requested isolated "
            "perturbation load under the Section 2.6 protocol: "
            f"dataset={dataset}, model={model_label}, "
            f"ratio={float(perturbation_ratio):g}, added={total_added}, "
            f"target={total_target}, maximum_available={total_available}, "
            f"fraction={realized_target_fraction:.3f} < "
            f"{float(minimum_realized_fraction):.3f}. Reduce the maximum "
            "perturbation ratio or the isolation guard."
        )

    metrics = classification_from_confusion(confusion)
    layer_df = pd.DataFrame(layer_rows)
    totals = layer_df[["mac_ops", "analog_mac_ops", "graded_mac_ops", "ac_ops", "synops", "transmission_weighted_propagation", "neuron_updates", "output_spikes",
                       "cds_modulation_elements", "cds_state_elements"]].sum()
    mean_supported_release = (
        supported_release_sum / supported_count if supported_count else np.nan
    )
    mean_isolated_release = (
        isolated_release_sum / isolated_count if isolated_count else np.nan
    )
    transmission_selectivity = (
        1.0 - mean_isolated_release / mean_supported_release
        if supported_count and isolated_count and mean_supported_release > 0
        else np.nan
    )
    summary = {
        "dataset": dataset, "model": model_label,
        "isolated_perturbation_protocol": ISOLATED_PERTURBATION_PROTOCOL_VERSION,
        "perturbation_ratio": float(perturbation_ratio),
        "n_samples": n_samples, "added_event_bins": total_added,
        "added_event_bins_per_sample": total_added / max(n_samples, 1),
        "n_original_occupied_bins": total_original,
        "n_target_additions": total_target,
        "n_available_isolated_bins": total_available,
        "realized_perturbation_ratio": total_added / max(total_original, 1),
        "realized_target_fraction": realized_target_fraction,
        "isolation_guard_steps": int(isolation_guard_steps),
        **metrics,
        "mac_ops_per_sample": float(totals.mac_ops) / max(n_samples, 1),
        "analog_mac_ops_per_sample": float(totals.analog_mac_ops) / max(n_samples, 1),
        "graded_mac_ops_per_sample": float(totals.graded_mac_ops) / max(n_samples, 1),
        "ac_ops_per_sample": float(totals.ac_ops) / max(n_samples, 1),
        "synops_per_sample": float(totals.synops) / max(n_samples, 1),
        "transmission_weighted_propagation_per_sample": (
            float(totals.transmission_weighted_propagation)
            / max(n_samples, 1)
        ),
        "neuron_updates_per_sample": float(totals.neuron_updates) / max(n_samples, 1),
        "output_spikes_per_sample": float(totals.output_spikes) / max(n_samples, 1),
        "cds_modulation_elements_per_sample": float(totals.cds_modulation_elements) / max(n_samples, 1),
        "cds_state_elements_updated_per_sample": float(totals.cds_state_elements) / max(n_samples, 1),
        "mean_supported_release": mean_supported_release,
        "mean_isolated_release": mean_isolated_release,
        "transmission_selectivity": transmission_selectivity,
        "n_supported_original_bins": supported_count,
        "n_isolated_added_bins_for_selectivity": isolated_count,
    }
    return {
        "summary": summary,
        "temporal": pd.DataFrame(temporal_rows),
        "layerwise": layer_df,
        "cds": pd.DataFrame(cds_rows),
    }


DEFAULT_ENERGY_COSTS = {
    "e_mac_pj": 4.6,
    "e_ac_pj": 0.9,
    "e_mul_pj": 3.7,
    "e_compare_pj": 0.9,
    "e_neuron_update_pj": 0.9,
    "e_exp_pj": 10.0,
    "e_lut_pj": 1.0,
    "e_state_access_pj": 5.0,
}


PJ_PER_UJ = 1.0e6


def cds_element_updates(layer_df: pd.DataFrame, column: str) -> float:

    if layer_df.empty or column not in layer_df.columns:
        return 0.0
    return float(layer_df[column].sum())


def energy_decomposition(summary: dict, layer_df: pd.DataFrame, model: nn.Module,
                         costs: Optional[dict] = None, sequence_steps: int = 1) -> dict:

    c = dict(DEFAULT_ENERGY_COSTS); c.update(costs or {})
    n_samples = max(int(summary["n_samples"]), 1)
    mac = float(layer_df.mac_ops.sum()) / n_samples
    analog_mac = float(layer_df.analog_mac_ops.sum()) / n_samples
    graded_mac = float(layer_df.graded_mac_ops.sum()) / n_samples
    ac = float(layer_df.ac_ops.sum()) / n_samples
    neuron_updates = float(layer_df.neuron_updates.sum()) / n_samples
    dynamic_elements = cds_element_updates(layer_df, "cds_state_elements") / n_samples
    modulation_elements = cds_element_updates(layer_df, "cds_modulation_elements") / n_samples
    is_constant = summary.get("model") == "constant_release"
    state_updates = 0.0 if is_constant else dynamic_elements
    state_elements = state_updates / max(int(sequence_steps), 1)
    total_params = sum(p.numel() for p in model.parameters())
    cds_params = (sum(p.numel() for p in model.cds_layers.parameters())
                  if hasattr(model, "cds_layers") else 0)

    synaptic_energy = mac * c["e_mac_pj"] + ac * c["e_ac_pj"]
    neuron_energy = neuron_updates * c["e_neuron_update_pj"]


    if is_constant:


        mul_ops, add_ops = modulation_elements, 0.0
        compare_ops, nonlinear_ops = 0.0, 0.0
    else:
        mul_ops, add_ops = 5.0 * state_updates, 3.0 * state_updates
        compare_ops, nonlinear_ops = state_updates, state_updates
    state_accesses = 2.0 * state_updates
    cds_base = (mul_ops * c["e_mul_pj"] + add_ops * c["e_ac_pj"] +
                compare_ops * c["e_compare_pj"])
    cds_memory = state_accesses * c["e_state_access_pj"]
    cds_exact = cds_base + nonlinear_ops * c["e_exp_pj"] + cds_memory
    cds_lut = cds_base + nonlinear_ops * c["e_lut_pj"] + cds_memory
    total_static_parts = synaptic_energy + neuron_energy
    total_energy_exact_pj = total_static_parts + cds_exact
    total_energy_lut_pj = total_static_parts + cds_lut
    return {
        "dataset": summary["dataset"], "model": summary["model"],
        "isolated_perturbation_protocol": ISOLATED_PERTURBATION_PROTOCOL_VERSION,
        "perturbation_ratio": summary["perturbation_ratio"],
        "mac_ops_per_sample": mac, "analog_mac_ops_per_sample": analog_mac,
        "graded_mac_ops_per_sample": graded_mac, "ac_ops_per_sample": ac,
        "neuron_updates_per_sample": neuron_updates,
        "cds_state_updates_per_sample": state_updates,
        "cds_persistent_state_elements_per_sample": state_elements,
        "cds_persistent_state_memory_fp32_bytes": 4.0 * state_elements,
        "total_parameter_count": total_params, "cds_parameter_count": cds_params,
        "cds_mul_ops_per_sample": mul_ops, "cds_add_ops_per_sample": add_ops,
        "cds_nonlinear_ops_per_sample": nonlinear_ops,
        "cds_state_accesses_per_sample": state_accesses,
        "synaptic_energy_pj": synaptic_energy,
        "neuron_energy_pj": neuron_energy,
        "cds_arithmetic_memory_exact_pj": cds_exact,
        "cds_arithmetic_memory_lut_pj": cds_lut,
        "total_energy_exact_pj": total_energy_exact_pj,
        "total_energy_lut_pj": total_energy_lut_pj,
        "inference_energy_exact_uj_per_sample": total_energy_exact_pj / PJ_PER_UJ,
        "inference_energy_lut_uj_per_sample": total_energy_lut_pj / PJ_PER_UJ,
    }


def add_perturbation_derived_metrics(
    summary_df: pd.DataFrame, num_classes: int
) -> pd.DataFrame:
    out = summary_df.copy()
    out["chance_level"] = 1.0 / float(num_classes)
    out["perturbation_balanced_acc_retention"] = np.nan
    for model, indices in out.groupby("model").groups.items():
        sub = out.loc[indices]
        clean = sub[sub.perturbation_ratio == 0]
        if clean.empty:
            continue
        clean_ba = float(clean.balanced_acc.iloc[0])
        chance = 1.0 / float(num_classes)
        denom = clean_ba - chance
        out.loc[indices, "perturbation_balanced_acc_retention"] = (
            out.loc[indices, "balanced_acc"] - chance
        ) / (denom if abs(denom) > 1e-12 else np.nan)
    return out


def add_relative_efficiency(summary_df: pd.DataFrame, energy_df: pd.DataFrame,
                            num_classes: int) -> Tuple[pd.DataFrame, pd.DataFrame]:
    summary = summary_df.copy(); energy = energy_df.copy()
    clean_static = summary[
        (summary.model == "static") & (summary.perturbation_ratio == 0)
    ]
    if not clean_static.empty:
        base_ops = float(clean_static.synops_per_sample.iloc[0])
        quality = (summary.balanced_acc - 1.0 / num_classes) / (1.0 - 1.0 / num_classes)
        summary["chance_corrected_balanced_accuracy"] = quality
        summary["normalized_synops_vs_clean_static"] = summary.synops_per_sample / max(base_ops, 1e-12)
        summary["propagation_efficiency"] = quality / summary.normalized_synops_vs_clean_static.clip(lower=1e-12)
        if "transmission_weighted_propagation_per_sample" in summary:
            base_weighted = float(
                clean_static.transmission_weighted_propagation_per_sample.iloc[0]
            )
            summary["normalized_weighted_propagation_vs_clean_static"] = (
                summary.transmission_weighted_propagation_per_sample
                / max(base_weighted, 1e-12)
            )


            summary["transmission_efficiency"] = (
                quality
                / summary.normalized_weighted_propagation_vs_clean_static.clip(
                    lower=1e-12
                )
            )
    for scenario in ["exact", "lut"]:
        col = f"total_energy_{scenario}_pj"
        base = energy[
            (energy.model == "static") & (energy.perturbation_ratio == 0)
        ]
        if not base.empty:
            value = float(base[col].iloc[0])
            energy[f"normalized_energy_{scenario}_vs_clean_static"] = energy[col] / max(value, 1e-12)
            energy[f"net_energy_change_{scenario}_percent"] = 100.0 * (energy[col] - value) / max(value, 1e-12)
    return summary, energy


def run_dataset_analysis(dataset: str, modality: str, seed: int, data_root: str,
                         results_26_root: str, out_root: str,
                         config_cls, build_datasets, build_model,
                         batch_size: Optional[int] = None, num_workers: int = 4,
                         device_text: str = "cuda:0",
                         perturbation_ratios: Sequence[float] = (0, .025, .05, .1),
                         max_batches: int = 0, perturbation_repeats: int = 3,
                         isolation_guard_steps: int = 4,
                         minimum_realized_fraction: float = .95,
                         ablation_root: Optional[str] = None,
                         include_constant_release: bool = False,
                         energy_costs: Optional[dict] = None) -> Path:
    worker_init = set_seed(seed)
    device = torch.device(device_text if torch.cuda.is_available() and "cuda" in device_text else "cpu")
    root26, out = Path(results_26_root), Path(out_root) / dataset / f"seed_{seed}"
    logs = ensure_dir(out / "logs")

    requested_models = ["static", "cds"] + (["constant_release"] if include_constant_release else [])
    checkpoints = {}
    for label in requested_models:
        try:
            path = checkpoint_path(root26, dataset, seed, label,
                                   Path(ablation_root) if ablation_root else None)
            checkpoint = load_checkpoint_file(path, device)
            found_version = checkpoint.get("architecture_version")
            if found_version != ARCHITECTURE_VERSION:
                raise RuntimeError(
                    f"Checkpoint {path} uses architecture_version={found_version!r}; "
                    f"Section 2.7 requires {ARCHITECTURE_VERSION!r}. Rerun all paired "
                    "Section 2.6 Static/CDS training after moving CDS before Conv/Linear."
                )
            if checkpoint.get("transmission_order") != TRANSMISSION_ORDER:
                raise RuntimeError(
                    f"Checkpoint {path} records transmission_order="
                    f"{checkpoint.get('transmission_order')!r}; expected {TRANSMISSION_ORDER!r}."
                )
            checkpoint_protocol = checkpoint.get("isolated_perturbation_protocol")
            if checkpoint_protocol != ISOLATED_PERTURBATION_PROTOCOL_VERSION:
                raise RuntimeError(
                    f"Checkpoint {path} records isolated_perturbation_protocol="
                    f"{checkpoint_protocol!r}; expected "
                    f"{ISOLATED_PERTURBATION_PROTOCOL_VERSION!r}. Rerun Section "
                    "2.6 with the latest perturbation implementation."
                )
            if checkpoint.get("architecture_verified") is not True:
                raise RuntimeError(
                    f"Checkpoint {path} has no successful runtime architecture verification. "
                    "Rerun Section 2.6 with the verified presynaptic-CDS trainer."
                )
            checkpoints[label] = (path, checkpoint)
        except FileNotFoundError:
            if label == "constant_release":
                print("[Section 2.7] constant-release checkpoint not found; control will be skipped.")
            else:
                raise

    verify_matched_checkpoint_configs(checkpoints)
    reference = checkpoints["static"][1]
    cfg = dataclass_from_checkpoint(config_cls, reference, {
        "data_root": data_root, "seed": seed,
        **({"batch_size": batch_size} if batch_size is not None else {}),
    })
    _, test_set = normalize_dataset_splits(build_datasets(cfg))
    loader = DataLoader(test_set, batch_size=cfg.batch_size, shuffle=False,
                        num_workers=num_workers, worker_init_fn=worker_init,
                        generator=make_data_loader_generator(seed + 1),
                        pin_memory=(device.type == "cuda"))

    models = {}
    architecture_reports = {}
    try:
        verification_frame, _ = next(iter(loader))
    except StopIteration as exc:
        raise RuntimeError("Test loader is empty; architecture verification cannot run.") from exc
    verification_x = to_time_first(verification_frame, device)
    for label, (_path, checkpoint) in checkpoints.items():
        model_name = "static" if label == "static" else "cds"
        model_cfg = dataclass_from_checkpoint(config_cls, checkpoint, {
            "data_root": data_root, "seed": seed, "model": model_name,
            **({"batch_size": batch_size} if batch_size is not None else {}),
        })
        model = build_model(model_name, model_cfg, device)
        model.load_state_dict(checkpoint["model_state"], strict=True)
        report = verify_presynaptic_forward_order(model, verification_x)
        if report["architecture_version"] != ARCHITECTURE_VERSION:
            raise RuntimeError(f"Runtime verification returned an incompatible architecture: {report}")
        architecture_reports[label] = report
        models[label] = model

    all_summary, all_temporal, all_layer, all_cds, all_energy = [], [], [], [], []
    ratios = sorted(set(float(value) for value in perturbation_ratios))
    if not ratios or any(value < 0 for value in ratios):
        raise ValueError("perturbation_ratios must contain non-negative values.")
    if not any(abs(value) <= 1e-12 for value in ratios):
        raise ValueError("perturbation_ratios must include 0 for the clean reference.")
    if int(perturbation_repeats) < 1:
        raise ValueError("perturbation_repeats must be at least 1.")
    if int(isolation_guard_steps) < 1:
        raise ValueError("isolation_guard_steps must be at least 1.")
    if not 0 < float(minimum_realized_fraction) <= 1:
        raise ValueError("minimum_realized_fraction must lie in (0, 1].")
    for ratio in ratios:
        repeats = 1 if float(ratio) == 0 else int(perturbation_repeats)
        for repeat in range(repeats):
            matched_perturbation_seed = int(
                seed * 100003 + round(float(ratio) * 10000) * 101 + repeat
            )
            for label, model in models.items():
                result = evaluate_checkpoint(
                    model, label, loader, device, cfg, cfg.num_classes, dataset,
                    float(ratio), matched_perturbation_seed,
                    isolation_guard_steps=isolation_guard_steps,
                    minimum_realized_fraction=minimum_realized_fraction,
                    max_batches=max_batches,
                )
                row = dict(result["summary"]); row.update({
                    "seed": seed, "perturbation_repeat": repeat,
                    "modality": modality,
                    "section_2_7_analysis_version": SECTION_2_7_ANALYSIS_VERSION,
                    "architecture_version": ARCHITECTURE_VERSION,
                    "transmission_order": TRANSMISSION_ORDER,
                    "isolated_perturbation_protocol": (
                        ISOLATED_PERTURBATION_PROTOCOL_VERSION
                    ),
                    "architecture_verified": True,
                })
                all_summary.append(row)
                for key, target in [("temporal", all_temporal), ("layerwise", all_layer), ("cds", all_cds)]:
                    frame = result[key].copy()
                    if not frame.empty:
                        frame["seed"] = seed
                        frame["perturbation_repeat"] = repeat
                        frame["modality"] = modality
                        frame["section_2_7_analysis_version"] = (
                            SECTION_2_7_ANALYSIS_VERSION
                        )
                        frame["architecture_version"] = ARCHITECTURE_VERSION
                        frame["transmission_order"] = TRANSMISSION_ORDER
                        frame["isolated_perturbation_protocol"] = (
                            ISOLATED_PERTURBATION_PROTOCOL_VERSION
                        )
                        target.append(frame)
                energy = energy_decomposition(
                    row, result["layerwise"], model, energy_costs,
                    sequence_steps=int(getattr(cfg, "T", 1)),
                )
                energy.update({
                    "seed": seed, "perturbation_repeat": repeat,
                    "modality": modality,
                    "section_2_7_analysis_version": SECTION_2_7_ANALYSIS_VERSION,
                    "architecture_version": ARCHITECTURE_VERSION,
                    "transmission_order": TRANSMISSION_ORDER,
                    "isolated_perturbation_protocol": (
                        ISOLATED_PERTURBATION_PROTOCOL_VERSION
                    ),
                    "architecture_verified": True,
                })
                all_energy.append(energy)

    summary = add_perturbation_derived_metrics(
        pd.DataFrame(all_summary), cfg.num_classes
    )
    energy = pd.DataFrame(all_energy)
    summary, energy = add_relative_efficiency(summary, energy, cfg.num_classes)
    temporal = pd.concat(all_temporal, ignore_index=True) if all_temporal else pd.DataFrame()
    layerwise = pd.concat(all_layer, ignore_index=True) if all_layer else pd.DataFrame()
    cds = pd.concat(all_cds, ignore_index=True) if all_cds else pd.DataFrame()

    summary.to_csv(logs / "efficiency_summary.csv", index=False)
    temporal.to_csv(logs / "temporal_activity.csv", index=False)
    layerwise.to_csv(logs / "layerwise_operations.csv", index=False)
    cds.to_csv(logs / "cds_state_dynamics.csv", index=False)
    energy.to_csv(logs / "energy_overhead_decomposition.csv", index=False)
    pd.DataFrame([energy_costs or DEFAULT_ENERGY_COSTS]).to_csv(logs / "energy_cost_assumptions.csv", index=False)
    save_json({
        "dataset": dataset, "modality": modality, "seed": seed,
        "data_root": data_root, "results_26_root": results_26_root,
        "perturbation_ratios": ratios,
        "perturbation_repeats": perturbation_repeats,
        "isolation_guard_steps": int(isolation_guard_steps),
        "minimum_realized_fraction": float(minimum_realized_fraction),
        "isolated_perturbation_protocol": (
            ISOLATED_PERTURBATION_PROTOCOL_VERSION
        ),
        "max_batches": max_batches, "models": list(models),
        "architecture_version": ARCHITECTURE_VERSION,
        "section_2_7_analysis_version": SECTION_2_7_ANALYSIS_VERSION,
        "transmission_order": TRANSMISSION_ORDER,
        "architecture_verified": True,
        "architecture_verification": architecture_reports,
        "checkpoint_paths": {k: str(v[0]) for k, v in checkpoints.items()},
        "config": asdict(cfg),
    }, logs / "analysis_config.json")
    print(f"Saved Section 2.7 {dataset} analysis to {logs}")
    return logs
